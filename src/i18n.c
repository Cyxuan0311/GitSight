void gs_set_lang(GsLang lang) {
    g_lang = lang;
}

GsLang gs_get_lang(void) {
    return g_lang;
}

void gs_set_lang_str(const char *s) {
    g_lang = (s && (strncmp(s, "zh", 2) == 0)) ? GS_LANG_ZH : GS_LANG_EN;
}

const char *gs_t(const char *en) {
    if (!en) return "";
    if (g_lang != GS_LANG_ZH) return en;
    for (size_t i = 0; i < sizeof(TABLE) / sizeof(TABLE[0]); i++)
        if (strcmp(TABLE[i].en, en) == 0) return TABLE[i].zh;
    return en;
}

const char *gs_weekday(int i) {
    static const char *en[] = { "Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat" };
    static const char *zh[] = { "周日", "周一", "周二", "周三", "周四", "周五", "周六" };
    if (i < 0 || i > 6) i = 0;
    return g_lang == GS_LANG_ZH ? zh[i] : en[i];
}

void *gs_i18n_table_json(void) {
    cJSON *arr = cJSON_CreateArray();
    for (size_t i = 0; i < sizeof(TABLE) / sizeof(TABLE[0]); i++) {
        cJSON *o = cJSON_CreateObject();
        cJSON_AddStringToObject(o, "en", TABLE[i].en);
        cJSON_AddStringToObject(o, "zh", TABLE[i].zh);
        cJSON_AddItemToArray(arr, o);
    }
    return arr;
}
