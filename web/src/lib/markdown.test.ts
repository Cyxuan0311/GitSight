import { describe, expect, it } from 'vitest';

import { markdownToText, parseInline, parseMarkdown, safeHref, splitTableRow } from './markdown';

describe('safeHref', () => {
  it('keeps the schemes a report links to', () => {
    expect(safeHref('https://github.com/curl/curl')).toBe('https://github.com/curl/curl');
    expect(safeHref('http://example.test/p/1')).toBe('http://example.test/p/1');
    expect(safeHref('mailto:a@example.test')).toBe('mailto:a@example.test');
  });

  it('drops schemes that could carry script', () => {
    expect(safeHref('javascript:alert(1)')).toBeUndefined();
    expect(safeHref('JavaScript:alert(1)')).toBeUndefined();
    expect(safeHref('data:text/html,<script>alert(1)</script>')).toBeUndefined();
    expect(safeHref('vbscript:msgbox(1)')).toBeUndefined();
  });

  // The exporter writes "#" when a pull request carries no URL, and a relative
  // path would otherwise resolve against the console's own origin.
  it('drops anything without an explicit scheme', () => {
    expect(safeHref('#')).toBeUndefined();
    expect(safeHref('/settings')).toBeUndefined();
    expect(safeHref('settings')).toBeUndefined();
    expect(safeHref('   ')).toBeUndefined();
  });
});

describe('splitTableRow', () => {
  it('handles optional leading and trailing pipes', () => {
    expect(splitTableRow('| a | b |')).toEqual(['a', 'b']);
    expect(splitTableRow('a | b')).toEqual(['a', 'b']);
  });

  it('keeps a quoted comma inside one cell', () => {
    expect(splitTableRow('| k | "bug, ui" |')).toEqual(['k', 'bug, ui']);
    expect(splitTableRow('| s | "say ""hi""" |')).toEqual(['s', 'say "hi"']);
  });

  it('splits on pipes, not commas', () => {
    expect(splitTableRow('a,b')).toEqual(['a,b']);
  });

  it('unescapes a literal pipe', () => {
    expect(splitTableRow('| a \\| b | c |')).toEqual(['a | b', 'c']);
  });
});

describe('parseInline', () => {
  it('reads the inline forms the exporter emits', () => {
    expect(parseInline('**Repository**: acme/gadget')).toEqual([
      { text: 'Repository', strong: true },
      { text: ': acme/gadget' },
    ]);
    expect(parseInline('*emphasis*')).toEqual([{ text: 'emphasis', emphasis: true }]);
    expect(parseInline('`aaaa111`')).toEqual([{ text: 'aaaa111', code: true }]);
  });

  it('reads a link and keeps its label styling', () => {
    expect(parseInline('[42](https://example.test/p/42)')).toEqual([
      { text: '42', href: 'https://example.test/p/42' },
    ]);
    expect(parseInline('[`aaaa111`](https://example.test/c/1)')).toEqual([
      { text: 'aaaa111', code: true, href: 'https://example.test/c/1' },
    ]);
  });

  it('keeps a link whose scheme is not allowed as plain text', () => {
    expect(parseInline('[click](javascript:alert(1))')).toEqual([{ text: 'click' }]);
  });

  it('leaves a lone marker as text', () => {
    expect(parseInline('a * b')).toEqual([{ text: 'a * b' }]);
    expect(parseInline('2 ** 3')).toEqual([{ text: '2 ** 3' }]);
  });

  it('treats a backslash as an escape', () => {
    expect(parseInline('a \\* b')).toEqual([{ text: 'a * b' }]);
  });
});

describe('parseMarkdown', () => {
  it('reads the shape the md exporter produces', () => {
    const blocks = parseMarkdown(
      [
        '# GitSight Report',
        '',
        '**Repository**: acme/gadget',
        '**Period**:     last 7 days',
        '',
        '---',
        '',
        '## Repository',
        '',
        '| Metric          | Value |',
        '|-----------------|-------|',
        '| Stars           | 1234  |',
        '| Default branch  | main  |',
        '',
        '```',
        '10-17 |##### 1',
        '```',
        '',
        '*Generated by GitSight*',
      ].join('\n'),
    );

    expect(blocks.map((b) => b.kind)).toEqual([
      'heading',
      'paragraph',
      'hr',
      'heading',
      'table',
      'code',
      'paragraph',
    ]);

    const table = blocks[4];
    if (table?.kind !== 'table') throw new Error('expected a table');
    expect(table.header).toEqual([[{ text: 'Metric' }], [{ text: 'Value' }]]);
    expect(table.rows).toHaveLength(2);
    expect(table.rows[0]?.[1]?.[0]?.text).toBe('1234');
  });

  it('reads column alignment', () => {
    const blocks = parseMarkdown(['| a | b | c |', '|:--|:-:|--:|', '| 1 | 2 | 3 |'].join('\n'));
    const table = blocks[0];
    if (table?.kind !== 'table') throw new Error('expected a table');
    expect(table.align).toEqual(['left', 'center', 'right']);
  });

  it('joins the soft-wrapped lines of a paragraph', () => {
    const blocks = parseMarkdown('**Repository**: acme/gadget\n**Period**: last 7 days');
    expect(blocks).toHaveLength(1);
    expect(blocks[0]?.kind).toBe('paragraph');
  });

  it('terminates a table at the first non-table line', () => {
    const blocks = parseMarkdown(
      ['| a | b |', '|---|---|', '| 1 | 2 |', 'after', '', '| a | b |', '|---|---|', '| 3 | 4 |'].join('\n'),
    );
    const tables = blocks.filter((b) => b.kind === 'table');
    expect(tables).toHaveLength(2);
    if (tables[0]?.kind === 'table') expect(tables[0].rows).toHaveLength(1);
  });

  it('does not mistake a table separator for a rule', () => {
    const blocks = parseMarkdown(['| a | b |', '|---|---|'].join('\n'));
    expect(blocks.some((b) => b.kind === 'hr')).toBe(false);
    expect(blocks[0]?.kind).toBe('table');
  });

  it('survives an unterminated code fence', () => {
    const blocks = parseMarkdown('```\n10-17 |##\n');
    expect(blocks).toEqual([{ kind: 'code', text: '10-17 |##' }]);
  });

  it('keeps the fence info string as the code language', () => {
    const blocks = parseMarkdown('```bash\nls -la\n```');
    expect(blocks).toEqual([{ kind: 'code', text: 'ls -la', lang: 'bash' }]);
    // No info at all stays absent instead of becoming an empty string.
    expect(parseMarkdown('```\nx\n```')).toEqual([{ kind: 'code', text: 'x' }]);
  });

  it('never produces raw html from a document', () => {
    const blocks = parseMarkdown('| t |\n|---|\n| <script>alert(1)</script> |');
    const table = blocks[0];
    if (table?.kind !== 'table') throw new Error('expected a table');
    // The markup survives only as text, which React then escapes.
    expect(table.rows[0]?.[0]?.[0]?.text).toBe('<script>alert(1)</script>');
  });
});

describe('markdownToText', () => {
  it('flattens a document back to text', () => {
    const text = markdownToText(
      ['# Title', '', '**Key**: value', '', '| a | b |', '|---|---|', '| 1 | 2 |'].join('\n'),
    );
    expect(text).toContain('Title');
    expect(text).toContain('Key: value');
    expect(text).toContain('1 | 2');
  });
});